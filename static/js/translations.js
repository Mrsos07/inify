// الحصول على اللغة الحالية
function getCurrentLanguage() {
    return localStorage.getItem('inify_language') || 'ar';
}

// تعيين اللغة
function setLanguage(lang) {
    localStorage.setItem('inify_language', lang);
    applyLanguage(lang);
}

// تبديل اللغة
function toggleLanguage() {
    const currentLang = getCurrentLanguage();
    const newLang = currentLang === 'ar' ? 'en' : 'ar';
    setLanguage(newLang);
    return newLang;
}

// ترجمة نص
function t(text) {
    const lang = getCurrentLanguage();
    if (lang === 'ar') return text;
    return translations.en[text] || text;
}

// تطبيق اللغة على الصفحة
function applyLanguage(lang) {
    // تغيير اتجاه الصفحة
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    
    // تحديث زر اللغة
    const langBtn = document.getElementById('langToggleBtn');
    if (langBtn) {
        langBtn.innerHTML = lang === 'ar' ? '🌐 EN' : '🌐 عربي';
    }
    
    // ترجمة جميع العناصر التي لها data-translate
    document.querySelectorAll('[data-translate]').forEach(el => {
        const key = el.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            el.textContent = translations[lang][key];
        } else if (lang === 'ar') {
            el.textContent = key;
        }
    });
    
    // ترجمة العناصر التي لها data-translate-placeholder
    document.querySelectorAll('[data-translate-placeholder]').forEach(el => {
        const key = el.getAttribute('data-translate-placeholder');
        if (translations[lang] && translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });
    
    // ترجمة النصوص داخل الصفحة
    translatePageContent(lang);
}

// ترجمة محتوى الصفحة
function translatePageContent(lang) {
    if (lang === 'ar') {
        // إعادة تحميل الصفحة للعربية (النص الأصلي)
        // لا نحتاج ترجمة
        return;
    }
    
    // البحث عن النصوص وترجمتها
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        null,
        false
    );
    
    const textNodes = [];
    while (walker.nextNode()) {
        textNodes.push(walker.currentNode);
    }
    
    textNodes.forEach(node => {
        const text = node.textContent.trim();
        if (text && translations.en[text]) {
            node.textContent = node.textContent.replace(text, translations.en[text]);
        }
    });
}

// تهيئة اللغة عند تحميل الصفحة
document.addEventListener('DOMContentLoaded', function() {
    const lang = getCurrentLanguage();
    applyLanguage(lang);
});

// تصدير الدوال
window.InifyTranslate = {
    getCurrentLanguage,
    setLanguage,
    toggleLanguage,
    t,
    applyLanguage
};
